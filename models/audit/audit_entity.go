// AuditLogEntity mirrors the append-only audit_logs table.
// Before/After hold JSON documents; never put secrets in them.
type AuditLogEntity struct {
	ID         int64   `gorm:"primaryKey;->"` // generated by the database
	TenantID   *string `gorm:"type:uuid"`
	ActorID    *string `gorm:"type:uuid"`
	Action     string  `gorm:"not null"`
	EntityType string  `gorm:"not null"`
	EntityID   *string `gorm:"type:uuid"`
	Before     []byte  `gorm:"type:jsonb"`
	After      []byte  `gorm:"type:jsonb"`
	IP         *string `gorm:"type:inet"`
	UserAgent  *string
	CreatedAt  time.Time
}

func (AuditLogEntity) TableName() string { return "audit_logs" }

// Client describes where a request came from.
type Client struct {
	IP        string
	UserAgent string
}

// Entry describes one audit record. Before/After are marshaled to JSON (nil = NULL).
type Entry struct {
	TenantID   string
	ActorID    string
	Action     string
	EntityType string
	EntityID   string
	Before     any
	After      any
	Client     Client
}

// New builds an AuditLogEntity from e.
func New(e Entry) *AuditLogEntity {
	return &AuditLogEntity{
		TenantID:   nonEmpty(e.TenantID),
		ActorID:    nonEmpty(e.ActorID),
		Action:     e.Action,
		EntityType: e.EntityType,
		EntityID:   nonEmpty(e.EntityID),
		Before:     marshal(e.Before),
		After:      marshal(e.After),
		IP:         nonEmpty(e.Client.IP),
		UserAgent:  nonEmpty(Truncate(e.Client.UserAgent, 500)),
	}
}

func marshal(v any) []byte {
	if v == nil {
		return nil
	}
	b, err := json.Marshal(v)
	if err != nil {
		// Callers pass plain DTOs/maps; fall back to a marker instead of losing the record.
		return []byte(`{"marshal_error":true}`)
	}
	return b
}

func nonEmpty(s string) *string {
	if s == "" {
		return nil
	}
	return &s
}

// Truncate cuts s to at most n bytes without splitting a UTF-8 sequence.
func Truncate(s string, n int) string {
	if len(s) <= n {
		return s
	}
	for n > 0 && !utf8.RuneStart(s[n]) {
		n--
	}
	return s[:n]
}
