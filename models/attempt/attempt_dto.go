package attempt

import (
	modelMedia "doexam/models/media"
	"encoding/json"
	"time"
)

// Limits.
const (
	MaxEventsPerBatch = 200
	MaxShortAnswer    = 500
	MaxEssayChars     = 20000
)

// StartInput is the body of POST /api/v1/attempts (start or resume).
type StartInput struct {
	SessionID string `json:"session_id"`
	Token     string `json:"token"`
}

// ClientEvent is one event from the exam client.
type ClientEvent struct {
	ClientEventID string          `json:"client_event_id"` // UUID generated by the client; idempotency key
	ClientSeq     int             `json:"client_seq"`      // increasing per attempt on the client
	Type          string          `json:"type"`
	AttemptItemID string          `json:"attempt_item_id"`
	Payload       json.RawMessage `json:"payload"`
	ClientTS      *time.Time      `json:"client_ts"`
}

// EventsInput is the body of POST /api/v1/attempts/:id/events.
type EventsInput struct {
	Events []ClientEvent `json:"events"`
}

// Rejected explains why one event was not applied.
type Rejected struct {
	ClientEventID string `json:"client_event_id"`
	Reason        string `json:"reason"`
}

// SyncDTO answers an event batch. Re-sending a batch is always safe.
type SyncDTO struct {
	Accepted   int        `json:"accepted"`
	Duplicates int        `json:"duplicates"`
	Rejected   []Rejected `json:"rejected"`
	Status     Status     `json:"status"`
	DeadlineAt time.Time  `json:"deadline_at"`
	ServerTime time.Time  `json:"server_time"`
	// AnnouncementCursor changes whenever an announcement of the session is sent or
	// retracted; the client then reloads GET /my/announcements ("" = none).
	AnnouncementCursor string `json:"announcement_cursor"`
}

// ExtendInput is the body of POST /api/v1/attempts/:id/extend.
type ExtendInput struct {
	Minutes int `json:"minutes"`
}

// GrantPlaysInput is the body of POST /api/v1/attempts/:id/grant-plays: extra plays for
// every audio clip with a play limit (e.g. the speaker failed).
type GrantPlaysInput struct {
	Plays int `json:"plays"`
}

// ---- delivery (participant view: never contains answer keys) ----

// OptionView is one displayed option.
type OptionView struct {
	ID   string `json:"id"`
	Body string `json:"body"`
}

// StimulusView is a stimulus shown with an item.
type StimulusView struct {
	ID    string `json:"id"`
	Title string `json:"title"`
	Body  string `json:"body"`
}

// ItemView is one item as the participant sees it.
type ItemView struct {
	ID        string          `json:"id"` // attempt item id
	Position  int             `json:"position"`
	Type      string          `json:"type"`
	Stem      string          `json:"stem"`
	Options   []OptionView    `json:"options,omitempty"` // in the participant's order
	Input     string          `json:"input,omitempty"`
	MaxWords  *int            `json:"max_words,omitempty"`
	Stimulus  *StimulusView   `json:"stimulus,omitempty"`
	MaxPoints float64         `json:"max_points"`
	Response  json.RawMessage `json:"response"`
	Flagged   bool            `json:"flagged"`
}

// SectionView is a section of the attempt.
type SectionView struct {
	ID           string     `json:"id"` // attempt section id
	Title        string     `json:"title"`
	Instructions *string    `json:"instructions"`
	SortOrder    int        `json:"sort_order"`
	State        string     `json:"state"` // pending | active | closed
	DeadlineAt   *time.Time `json:"deadline_at"`
	AllowRevisit bool       `json:"allow_revisit"`
	ItemCount    int        `json:"item_count"`
	Items        []ItemView `json:"items"` // only for active sections
}

// AttemptView is the exam as the participant takes it.
type AttemptView struct {
	ID              string          `json:"id"`
	SessionID       string          `json:"session_id"`
	ExamTitle       string          `json:"exam_title"`
	Instructions    *string         `json:"instructions"`
	Status          Status          `json:"status"`
	Navigation      string          `json:"navigation"`
	SectionMode     string          `json:"section_mode"` // shared | sequential
	SecurityProfile string          `json:"security_profile"`
	Settings        json.RawMessage `json:"settings"`
	StartedAt       time.Time       `json:"started_at"`
	DeadlineAt      time.Time       `json:"deadline_at"`
	ServerTime      time.Time       `json:"server_time"`
	Sections        []SectionView   `json:"sections"`
	// Media maps every data-media-id in the delivered items to a signed link.
	Media map[string]modelMedia.Ref `json:"media"`
	// MediaPlays counts the plays recorded per audio clip (data-media-id); ExtraPlays is
	// added by proctors to every clip's data-max-plays.
	MediaPlays map[string]int `json:"media_plays"`
	ExtraPlays int            `json:"extra_plays"`
}

// ---- results ----

// ItemResult is a per-item result shown to the participant when allowed.
type ItemResult struct {
	Position    int      `json:"position"`
	Score       *float64 `json:"score"`
	MaxPoints   float64  `json:"max_points"`
	IsCorrect   *bool    `json:"is_correct"`
	Explanation *string  `json:"explanation,omitempty"`
}

// ResultDTO is GET /api/v1/attempts/:id/result.
type ResultDTO struct {
	AttemptID     string       `json:"attempt_id"`
	Status        Status       `json:"status"`
	Visible       bool         `json:"visible"` // false = not released yet (result_visibility)
	RawScore      *float64     `json:"raw_score,omitempty"`
	MaxScore      *float64     `json:"max_score,omitempty"`
	FinalScore    *float64     `json:"final_score,omitempty"`
	Passed        *bool        `json:"passed,omitempty"`
	PendingManual int          `json:"pending_manual"`
	Items         []ItemResult `json:"items,omitempty"`
	// Media maps every data-media-id in the explanations to a signed link.
	Media map[string]modelMedia.Ref `json:"media,omitempty"`
}

// MyAttemptDTO is one row of GET /api/v1/my/attempts.
type MyAttemptDTO struct {
	ID          string     `json:"id"`
	ExamID      string     `json:"exam_id"`
	ExamTitle   string     `json:"exam_title"`
	SessionID   string     `json:"session_id"`
	AttemptNo   int        `json:"attempt_no"`
	Status      Status     `json:"status"`
	StartedAt   time.Time  `json:"started_at"`
	DeadlineAt  time.Time  `json:"deadline_at"`
	SubmittedAt *time.Time `json:"submitted_at"`
}

// ---- proctor dashboard ----

// MonitorRow is one participant on the proctor dashboard.
type MonitorRow struct {
	UserID      string     `json:"user_id"`
	Username    string     `json:"username"`
	FullName    string     `json:"full_name"`
	Seat        *string    `json:"seat"`
	Attendance  string     `json:"attendance"`
	AttemptID   *string    `json:"attempt_id"`
	Status      *Status    `json:"status"` // nil = not started
	Answered    int        `json:"answered"`
	ItemCount   int        `json:"item_count"`
	DeadlineAt  *time.Time `json:"deadline_at"`
	LastSeenAt  *time.Time `json:"last_seen_at"`
	Violations  int        `json:"violations"`
	DeviceBound bool       `json:"device_bound"`
	FinalScore  *float64   `json:"final_score"`
	// Idle: in progress without a sync for longer than the monitor's idle threshold.
	Idle bool `json:"idle"`
	// ViolationCounts per type (focus_lost, fullscreen_exit, device_changed); Violations is their sum.
	ViolationCounts map[string]int `json:"violation_counts"`
	LastViolationAt *time.Time     `json:"last_violation_at"`
	LockedAt        *time.Time     `json:"locked_at"` // last LOCKED event
	SubmittedAt     *time.Time     `json:"submitted_at"`
}

// MonitorView selects the participants of GET /sessions/:id/monitor/list.
type MonitorView string

// Monitor views (DOCS/PLAN/15-MONITOR-KARTU.md §1).
const (
	ViewAll        MonitorView = "all"
	ViewViolations MonitorView = "violations"
	ViewIdle       MonitorView = "idle"
	ViewLocked     MonitorView = "locked"
	ViewNotStarted MonitorView = "not_started"
	ViewInProgress MonitorView = "in_progress"
	ViewSubmitted  MonitorView = "submitted"
)

// MonitorViews lists the valid views.
var MonitorViews = []MonitorView{ViewAll, ViewViolations, ViewIdle, ViewLocked, ViewNotStarted, ViewInProgress, ViewSubmitted}

// Violation types as the monitor names them (lowercase of the event types).
const (
	ViolationFocusLost      = "focus_lost"
	ViolationFullscreenExit = "fullscreen_exit"
	ViolationDeviceChanged  = "device_changed"
)

// ViolationTypes lists the valid violation_type filters.
var ViolationTypes = []string{ViolationFocusLost, ViolationFullscreenExit, ViolationDeviceChanged}

// MaxWatch is how many participants one proctor may watch at once.
const MaxWatch = 25

// MonitorFilter narrows the monitor. GroupID and Seat also scope the counts; Query,
// View, ViolationType and UserIDs only pick the rows.
type MonitorFilter struct {
	View          MonitorView
	ViolationType string
	GroupID       string
	Seat          string // seat prefix, e.g. "A-"
	Query         string // name, username or seat
	UserIDs       []string
	Page          int
	PerPage       int
}

// WatchInput is the body of POST /api/v1/sessions/:id/monitor/watch.
type WatchInput struct {
	UserIDs []string `json:"user_ids"`
}

// MonitorDTO is GET /api/v1/sessions/:id/monitor.
type MonitorDTO struct {
	SessionID  string         `json:"session_id"`
	Status     string         `json:"status"`
	ServerTime time.Time      `json:"server_time"`
	Counts     map[string]int `json:"counts"` // legacy: not_started, in_progress, locked, submitted, graded; list/watch: total, not_started, in_progress, locked, submitted (incl. graded), idle, violations
	Rows       []MonitorRow   `json:"rows"`
}
